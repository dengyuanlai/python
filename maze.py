def print_maze(maze):
    for row in maze:
        print(' '.join(row))
    print()


def find_position(maze, target):
    for r, row in enumerate(maze):
        for c, cell in enumerate(row):
            if cell == target:
                return (r, c)
    return None


def solve(maze, row, col, end):
    """
    Recursively attempt to navigate from (row, col) to end.
    Returns True if a path to the exit is found, False otherwise.
    """
    rows = len(maze)
    cols = len(maze[0])

    # Out of bounds
    if row < 0 or row >= rows or col < 0 or col >= cols:
        return False

    cell = maze[row][col]

    # Hit a wall, already visited, or dead-end marker
    if cell == '#' or cell == '.' or cell == 'X':
        return False

    # Reached the end
    if (row, col) == end:
        maze[row][col] = 'E'
        return True

    # Mark current cell as part of the active path
    if cell != 'S':
        maze[row][col] = '.'

    # Explore all four directions: down, right, up, left
    for dr, dc in [(-1, 0), (0, 1), (1, 0), (0, -1)]:
        if solve(maze, row + dr, col + dc, end):
            return True

    # No direction worked — backtrack
    if cell != 'S':
        maze[row][col] = 'X'
    return False


def main():
    print("=== Original Maze ===")
    print_maze(MAZE)

    start = find_position(MAZE, 'S')
    end = find_position(MAZE, 'E')

    if start is None or end is None:
        print("Maze must have an 'S' (start) and 'E' (end).")
        return

    print(f"Start: {start}  End: {end}\n")

    if solve(MAZE, start[0], start[1], end):
        print("=== Solved Maze ===")
        print("'.' = solution path   'X' = dead end\n")
        print_maze(MAZE)
    else:
        print("No solution found.")


if __name__ == "__main__":
    main()
